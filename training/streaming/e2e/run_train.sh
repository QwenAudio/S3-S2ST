export STREAMING_S2ST_TALKER_CKPT=${S3_ROOT}/checkpoints/offline/iter_0010000
export RESUME_TRAINING=${RESUME_TRAINING:-0}
if [[ $RESUME_TRAINING == 1 ]]; then
  [[ -s $EXP_DIR/latest_checkpointed_iteration.txt ]]
  export INIT_CKPT_DIR=${S3_INIT_CKPT:?}
  export CKPT_FORMAT_ARGS='--ckpt-format torch_dist --use-checkpoint-opt_param-scheduler'
else
  [[ ! -e $EXP_DIR/latest_checkpointed_iteration.txt ]] || { echo 'Refusing fresh overwrite'; exit 1; }
  export INIT_CKPT_DIR=${S3_INIT_CKPT:?}
fi
export STREAMING_S2ST_TRAIN_LIST=${TRAIN_DATA_LIST:?}
export STREAMING_S2ST_VALID_LIST=${VALID_DATA_LIST:-$TRAIN_DATA_LIST}
export S2ST_PRESERVE_COSYVOICE_CHECKPOINT=1 STREAMING_S2ST_SKIP_TALKER_OVERLAY=1
export STREAMING_S2ST_CODEC_ENVELOPE=1 STREAMING_S2ST_INJECTED_DUAL_BOS=0 STREAMING_S2ST_FINAL_CODEC_EOS_ONLY=0
export STREAMING_S2ST_CODEC_BOS_TOKEN_ID=59049 STREAMING_S2ST_CODEC_EOS_TOKEN_ID=59050 STREAMING_S2ST_CODEC_BLANK_COUNT=5
export STREAMING_S2ST_TALKER_ONLY_SEGMENT_PADDING=0 STREAMING_S2ST_CODEC_RESERVATION_MARGIN=4
export TP_SIZE=1 PP_SIZE=1 CP_SIZE=1 EP_SIZE=1 WORLD_SIZE=1 RANK=0 NPROC_PER_NODE=8
export MASTER_ADDR=127.0.0.1 MASTER_PORT=12979 CUDA_VISIBLE_DEVICES=0,1,2,3,4,5,6,7
export GLOBAL_BATCH_SIZE=64 MICRO_BATCH_SIZE=1 LR=1e-6 STREAM_GATE_LR_SCALE=10.0
export LR_WARMUP_ITERS=0 TRAIN_ITERS=${TRAIN_ITERS:-5000} SAVE_INTERVAL=1000
export RECOMPUTE_ARGS='--recompute-granularity full --recompute-method uniform --recompute-num-layers 1'
export PYTORCH_CUDA_ALLOC_CONF=expandable_segments:True
export STREAMING_S2ST_BLOCK640_LOOKAHEAD160=1 STREAMING_TRUE_ENCODER=1 STREAMING_TRUE_ENCODER_CHUNK_MS=640
export STREAMING_ENCODER_LOOKAHEAD_MS=160 STREAMING_TRUE_ENCODER_OVERLAY=0
export STREAMING_TRUE_ADAPTOR=1 STREAMING_TRUE_ADAPTOR_CHUNK_TOKENS=8 STREAMING_WHISPER_FIXED_LOG_MEL_MAX=1.3904691073
export STREAMING_S2ST_TALKER_PACK_ISOLATION=1
export TEXT_LOSS_WEIGHT=1.0 STREAM_GATE_LOSS_WEIGHT=0.1 STREAM_GATE_WRITE_WEIGHT=1.0
export STREAMING_DEBUG_DISABLE_GATE=0 STREAM_GATE_BACKPROP_TO_THINKER=1
export STREAMING_S2ST_THINKER_LAYER_FUSION=1 STREAMING_S2ST_THINKER_LAYER_STRIDE=4
export STREAMING_S2ST_CONFIG_TEMPLATE=$EXP_DIR/backup/streaming_s2st_talker.yaml
export DATASET_CONFIG_PATH=$EXP_DIR/runtime/dataset.yaml TENSORBOARD_DIR=$EXP_DIR/tensorboard
export TORCHINDUCTOR_CACHE_DIR=$EXP_DIR/tmp/torchinductor TMPDIR="$EXP_DIR/tmp"
export STREAMING_AUDIO_READ_ATTEMPTS=3 STREAMING_FFMPEG_TIMEOUT_SEC=60 STREAMING_OSS_CONNECT_TIMEOUT_SEC=10
export ENABLE_SWANLAB=false PYTHONDONTWRITEBYTECODE=1
mkdir -p "$TMPDIR"
if [[ ${STREAMING_S2ST_PREPARE_ONLY:-0} != 1 ]]; then
  exec 9>"$EXP_DIR/train.lock"
  flock -n 9 || { echo 'Experiment already running'; exit 1; }
  echo $$ > "$EXP_DIR/train.pid"
fi
exec bash "$EXP_DIR/runtime/run_base.sh" "$@"
